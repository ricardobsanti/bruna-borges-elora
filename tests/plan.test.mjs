import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({window:{},read:()=>null});
for(const file of ['elora-data.js','elora-plan.js'])vm.runInContext(fs.readFileSync(new URL('../docs/'+file,import.meta.url),'utf8'),context);
const E=context.window.ELORA;
const sales={0:[3],1:[0],2:2,3:0,4:3,5:0,6:[1],7:0,8:0,9:1,10:1,11:[0,1,2,3]};
const content={...sales,0:[0],1:[1],6:[3],8:4,9:0};
assert.equal(E.evaluate(sales).priority,'vendas','A declared sales bottleneck should prioritize the sales pathway.');
assert.equal(E.evaluate(content).priority,'conteudo','A content bottleneck should produce a different primary focus.');
assert.notEqual(E.buildMonths(sales)[2].title,E.buildMonths(content)[2].title,'The two clients must receive substantively different six-month roadmaps.');
assert.equal(E.buildMonths(sales).length,6);
assert.ok(E.buildMonths(sales).every(m=>m.tasks.length===4&&m.prompt&&m.objective));
assert.equal(E.summarize(sales).completed,true);
assert.equal(E.summarize({...sales,6:[]}).completed,false,'A mandatory multi-select requires at least one answer.');
assert.deepEqual(E.evaluate({...sales,4:0}).weights,E.evaluate({...sales,4:5}).weights,'Revenue must not rank a person or change the needs assessment.');
assert.match(E.evaluate({...sales,10:0}).rhythm,/Microtarefas/);
assert.equal(E.evaluate({}).priority,'gestao');
assert.notEqual(E.buildMonths(sales)[0].id,E.buildMonths(content)[0].id,'Changing focus must not overwrite an earlier pathway’s records.');
console.log('Plan verification passed: sales vs content, six-month structure, missing answers, revenue neutrality, execution capacity and record isolation.');
